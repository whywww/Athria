export function errorText(error: unknown, language: Language): string {
  const message = error instanceof Error ? error.message : String(error);
  if (language !== "zh-CN") return message;
  const match = /^([A-Z][A-Z0-9_]+):\s*(.*)$/s.exec(message);
  return match && errorLabels[match[1]!] ? `${errorLabels[match[1]!]}：${match[2]}` : translate(message, language);
}
