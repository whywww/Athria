export function displayBuiltinTemplate<T extends { origin: string; id: string; name: string; intent: string; nodes: Array<{ name?: string }> }>(template: T, language: Language): T {
  if (template.origin !== "builtin" || language !== "zh-CN") return template;
  const copy = builtinTemplateText(template, language);
  return { ...template, ...copy, nodes: template.nodes.map((node) => node.name ? { ...node, name: translate(node.name, language) } : node) };
}
