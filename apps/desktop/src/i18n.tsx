import { createContext, useContext, useEffect, useState, type ReactNode } from "react";

export type Language = "en" | "zh-CN";
export const LANGUAGE_STORAGE_KEY = "athria:language";

export function systemLanguage(language = typeof navigator === "undefined" ? "en" : navigator.language): Language {
  return /^zh(?:-|$)/i.test(language) && !/^zh-(?:TW|HK|MO|Hant)(?:-|$)/i.test(language) ? "zh-CN" : "en";
}

export function readLanguage(storage: Pick<Storage, "getItem"> | null = typeof localStorage === "undefined" ? null : localStorage): Language {
  try {
    const saved = storage?.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === "en" || saved === "zh-CN") return saved;
  } catch { /* Storage can be disabled; use the system language. */ }
  return systemLanguage();
}
export function saveLanguage(value: Language, storage: Pick<Storage, "setItem"> | null = typeof localStorage === "undefined" ? null : localStorage): void {
  try { storage?.setItem(LANGUAGE_STORAGE_KEY, value); } catch { /* Session-only preference. */ }
}

const LanguageContext = createContext<{ language: Language; setLanguage: (value: Language) => void }>({ language: "en", setLanguage: () => {} });
let activeLanguage: Language = "en";
export function currentLanguage(): Language { return activeLanguage; }

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, updateLanguage] = useState<Language>(readLanguage);
  activeLanguage = language;
  const setLanguage = (value: Language) => {
    updateLanguage(value);
    saveLanguage(value);
  };
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() { return useContext(LanguageContext); }

